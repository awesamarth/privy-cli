// Generates one reference page per CLI command from the built CLI itself (`--help` and `privy schema`),
// so the website can never drift from the installed command surface.
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import { labels } from './guide-labels.ts';

const execFileAsync = promisify(execFile);

const root = fileURLToPath(new URL('../../', import.meta.url));
const cli = `${root}dist/cli.js`;
if (!existsSync(cli)) execFileSync('bun', ['run', 'build'], { cwd: root, stdio: 'inherit' });

const outDir = new URL('../src/content/docs/reference/', import.meta.url);
const run = (args: string[]) => {
  try {
    return execFileSync('node', [cli, ...args], { encoding: 'utf8', env: { ...process.env, NO_COLOR: '1', COLUMNS: '400' } });
  } catch (error: any) {
    return String(error.stdout ?? '');
  }
};

// Top-level groups and their order in the sidebar. Aliases are skipped to avoid duplicate pages.
const skip = new Set(['help', 'keys', 'cli schema', 'config get', 'config update']);
const globalFlags = new Set(['-V, --version', '--profile <name>', '--app <id>', '--account <id>', '--no-project', '--json', '-h, --help']);

function subcommands(path: string[]): string[] {
  const help = run([...path, '--help']);
  const section = help.split(/\nCommands:\n/)[1];
  if (!section) return [];
  const names: string[] = [];
  for (const line of section.split('\n')) {
    if (!line.trim()) break;
    const match = line.match(/^  (\S+)/);
    if (match) names.push(match[1]);
  }
  return names.filter(name => name !== 'help');
}

function collect(path: string[] = []): string[][] {
  const children = subcommands(path);
  if (path.length && !children.length) return [path];
  const leaves: string[][] = [];
  if (path.length && /Usage: privy [^\n]*\[command\]/.test(run([...path, '--help'])) === false) leaves.push(path);
  for (const child of children) {
    const next = [...path, child];
    if (skip.has(next.join(' '))) continue;
    leaves.push(...collect(next));
  }
  return leaves;
}

const esc = (text: unknown) => String(text ?? '').replace(/\s+/g, ' ').trim().replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '\\|');
const sentence = (text: string) => {
  let t = text.replace(/\s+/g, ' ').trim();
  if (!t) return t;
  t = t[0].toUpperCase() + t.slice(1);
  return /[.!?]$/.test(t) ? t : `${t}.`;
};
// Escape for Markdown, and wrap flags in code so typography doesn't turn "--yes" into an en dash.
const prose = (text: unknown) => esc(text).replace(/(^|[\s(])(--[a-z][\w-]*)/g, '$1`$2`');
const runAsync = async (args: string[]) => {
  try {
    return (await execFileAsync('node', [cli, ...args], { encoding: 'utf8', env: { ...process.env, NO_COLOR: '1', COLUMNS: '400' } })).stdout;
  } catch (error: any) {
    return String(error.stdout ?? '');
  }
};
const yaml = (text: string) => JSON.stringify(text.replace(/\s+/g, ' ').trim());

type Option = { flags: string; description?: string; default?: unknown };
type Argument = { name: string; description?: string; required?: boolean };

async function page(path: string[]) {
  const [help, schemaText] = await Promise.all([runAsync([...path, '--help']), runAsync(['schema', ...path])]);
  let schema: any = {};
  try {
    schema = JSON.parse(schemaText);
  } catch {}
  const command = `privy ${path.join(' ')}`;
  const usage = help.match(/^Usage: (.+)$/m)?.[1] ?? command;
  const description = sentence(schema.summary ?? schema.description ?? help.split('\n\n')[1]?.trim() ?? '');
  const options: Option[] = (schema.cli?.options ?? schema.options ?? []).filter((o: Option) => !globalFlags.has(o.flags));
  const args: Argument[] = schema.cli?.arguments ?? schema.arguments ?? [];
  const examples: string[] = schema.examples ?? [];
  const workflow = schema.workflow ?? {};
  const guides: { topic: string }[] = schema.guides ?? [];

  const lines: string[] = [
    '---',
    `title: ${yaml(command)}`,
    `description: ${yaml(`${description} Command reference for the unofficial Privy CLI.`)}`,
    '---',
    '',
    '<!-- Generated by site/scripts/gen-reference.ts from the CLI. Do not edit. -->',
    '',
    prose(description),
    '',
    '## Usage',
    '',
    '```sh',
    usage.trim(),
    '```',
  ];
  if (args.length) {
    lines.push('', '## Arguments', '', '| Argument | Description |', '| --- | --- |');
    for (const a of args) lines.push(`| \`${a.name}\`${a.required === false ? ' (optional)' : ''} | ${prose(sentence(a.description ?? '')) || '—'} |`);
  }
  if (options.length) {
    lines.push('', '## Options', '', '| Option | Description |', '| --- | --- |');
    for (const o of options) lines.push(`| \`${o.flags}\` | ${prose(sentence(o.description ?? ''))}${o.default !== undefined ? ` Default: \`${esc(o.default)}\`.` : ''} |`);
  }
  lines.push('', 'Global options such as `--app`, `--account` and `--profile` also apply. See the [command reference overview](/reference/).');
  if (examples.length) lines.push('', '## Examples', '', '```sh', ...examples, '```');

  const facts: string[] = [];
  if (typeof schema.mutation === 'boolean') facts.push(`- **Changes data:** ${schema.mutation ? 'yes. Preview with `--dry-run`, then run with `--yes` and any required confirmations.' : 'no, read-only.'}`);
  if (schema.scope) facts.push(`- **Scope:** ${esc(schema.scope)}`);
  for (const [key, label] of [['preflight', 'Before it runs'], ['production', 'Production apps'], ['verification', 'Verification'], ['retries', 'Retries'], ['warning', 'Caution']] as const) {
    if (workflow[key]) facts.push(`- **${label}:** ${prose(sentence(String(workflow[key])))}`);
  }
  if (facts.length) lines.push('', '## Behavior', '', ...facts);
  const topics = [...new Set(guides.map(g => g.topic))];
  if (topics.length) lines.push('', '## Related guides', '', ...topics.map(t => `- [${labels[t] ?? t}](/guides/${t}/)`));
  lines.push('', `Inspect the full contract locally with \`privy schema ${path.join(' ')}\`.`, '');
  return { command, description, body: lines.join('\n') };
}

await rm(outDir, { recursive: true, force: true });
const leaves = collect();
const index: Record<string, { command: string; description: string; href: string }[]> = {};
const pages: Awaited<ReturnType<typeof page>>[] = [];
for (let i = 0; i < leaves.length; i += 8) pages.push(...await Promise.all(leaves.slice(i, i + 8).map(page)));
for (const [n, path] of leaves.entries()) {
  const { command, description, body } = pages[n];
  const file = new URL(`${path.join('/')}.md`, outDir);
  await mkdir(new URL('.', file), { recursive: true });
  await writeFile(file, body);
  (index[path[0]] ??= []).push({ command, description, href: `/reference/${path.join('/')}/` });
}

const overview = [
  '---',
  'title: Command reference',
  'description: Every command in the unofficial Privy CLI, generated from the CLI itself.',
  'sidebar:',
  '  order: 0',
  '  label: Overview',
  '---',
  '',
  '<!-- Generated by site/scripts/gen-reference.ts from the CLI. Do not edit. -->',
  '',
  `Every command in the CLI (${leaves.length} in total), generated from \`--help\` and \`privy schema\`. Locally, \`privy cli search "your task"\` finds the right one.`,
  '',
  '## Global options',
  '',
  '| Option | Description |',
  '| --- | --- |',
  '| `--app <id>` | App to act on. Overrides a `privy.json` binding and the saved selection. |',
  '| `--account <id>` | Account (workspace) for account-scoped commands. |',
  '| `--profile <name>` | Saved login profile. Otherwise `PRIVY_PROFILE`, the project binding, then `default`. |',
  '| `--no-project` | Ignore `privy.json` in the current directory. |',
  '| `--json` | JSON output. Already the default. |',
  '',
  ...Object.entries(index).flatMap(([group, items]) => [
    `## ${group}`,
    '',
    ...items.map(i => `- [\`${i.command}\`](${i.href}): ${prose(i.description)}`),
    '',
  ]),
].join('\n');
await writeFile(new URL('index.md', outDir), overview);
console.log(`Generated ${leaves.length} command reference pages.`);
